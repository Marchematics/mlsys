PROVENANCE_HEADER = "% Generated by scripts/build_kbs_result_tables.py -- do not edit by hand.\n"


def fmt(value: float, digits: int = 4) -> str:
    """Format a number without a leading zero, e.g. .0362 and -.0005."""

    if value is None or not np.isfinite(value):
        return "n/a"
    text = f"{value:.{digits}f}"
    if text.startswith("-0"):
        text = "-" + text[2:]
    elif text.startswith("0"):
        text = text[1:]
    return text


def write(name: str, body: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / name).write_text(PROVENANCE_HEADER + body, encoding="utf-8")


def load_r080b_targets(dataset: str, seeds=None) -> dict[int, dict[str, list[float]]]:
    """Target -> policy -> per-seed gains, restricted to the requested seeds."""

    per_target: dict[int, dict[str, list[float]]] = {}
    for seed, root in sorted(R080B_SOURCES.items()):
        if seeds is not None and seed not in seeds:
            continue
        data_dir = root / dataset
        if not data_dir.exists():
            continue
        for target_dir in sorted(data_dir.glob("target*_seed*")):
            result_path = target_dir / "result.json"
            if not result_path.exists():
                continue
            result = json.loads(result_path.read_text(encoding="utf-8"))
            target = int(result["target_sensor"])
            bucket = per_target.setdefault(target, {})
            for key in [k for k, _ in DEPLOYABLE] + ABLATION_POLICIES + ["oracle_greedy"]:
                entry = result["metrics"][key]
                bucket.setdefault(key, []).append(float(entry["mean_prediction_gain"]))
                bucket.setdefault(f"{key}_ntr", []).append(float(entry["negative_transfer_rate"]))
                bucket.setdefault(f"{key}_contexts", []).append(float(entry["mean_selected_contexts"]))
    return per_target



