def complete_seeds(dataset: str, target_count: int = 32) -> set[int]:
    """Seeds whose run finished every target for this dataset."""

    counts: dict[int, int] = {}
    for seed, root in sorted(R080B_SOURCES.items()):
        data_dir = root / dataset
        if not data_dir.exists():
            continue
        counts[seed] = sum(1 for target_dir in data_dir.glob("target*_seed*") if (target_dir / "result.json").exists())
    return {seed for seed, count in counts.items() if count >= target_count}


def common_seeds() -> list[int]:
    """Seeds that finished every target of every dataset."""

    shared: set[int] | None = None
    for dataset in DATASETS:
        seeds = complete_seeds(dataset)
        shared = seeds if shared is None else (shared & seeds)
    return sorted(shared or set())


def target_level_bootstrap(values: np.ndarray, *, n_boot: int = 5000, seed: int = 0):
    """Cluster bootstrap over targets when a single value per target is available."""

    rng = np.random.default_rng(seed)
    n = values.size
    stats = np.empty(n_boot, dtype=float)
    for i in range(n_boot):
        idx = rng.integers(0, n, size=n)
        stats[i] = np.mean(values[idx])
    return float(np.mean(stats)), float(np.quantile(stats, 0.025)), float(np.quantile(stats, 0.975))


def hierarchical_bootstrap(
    per_target_runs: list[np.ndarray], *, n_boot: int = 5000, seed: int = 0
):
    """Two-level bootstrap: resample targets, then resample runs within a target."""

    rng = np.random.default_rng(seed)
    n_targets = len(per_target_runs)
    stats = np.empty(n_boot, dtype=float)
    for i in range(n_boot):
        targets = rng.integers(0, n_targets, size=n_targets)
        draws = [rng.choice(per_target_runs[t]) for t in targets]
        stats[i] = float(np.mean(draws))
    return float(np.mean(stats)), float(np.quantile(stats, 0.025)), float(np.quantile(stats, 0.975))


def table_redundancy() -> None:
    records = json.loads((R070_DIR / "aggregate.json").read_text())["records"]
    ratios = sorted({float(r["redundancy"]) for r in records})
    rows = []
    for ratio in ratios:
        subset = [r for r in records if float(r["redundancy"]) == ratio]

        def series(policy: str, metric: str = "mean_prediction_gain") -> np.ndarray:
            values = []
            for record in subset:
                entry = record["metrics"][policy]
                values.append(float(entry) if np.isscalar(entry) else float(entry[metric]))
            return np.asarray(values, dtype=float)

        static = series("oracle_static")
        rmur = series("mur_light")
        greedy = series("oracle")
        headroom = series("state_conditioning_headroom")
        rows.append(
            "{} & {} $\\pm$ {} & {} $\\pm$ {} & {} $\\pm$ {} & {} \\\\".format(
                "0" if ratio == 0 else fmt(ratio, 2),
                fmt(static.mean()),
                fmt(static.std(ddof=1)),
                fmt(rmur.mean()),
                fmt(rmur.std(ddof=1)),
                fmt(greedy.mean()),
                fmt(greedy.std(ddof=1)),
                fmt(headroom.mean()),
            )
        )
    body = "\n".join(
        [
            "% source: results/raw/R070_oracle_ladder_k16_b4_rgrid_s5_20260919_1540/aggregate.json",
            "\\begin{table}[t]",
            "\\centering",
            "\\small",
            "\\caption{Controlled redundancy study at $K=16$ and context budget four. Gains are",
            "loss reductions relative to the anchor-only predictor; results are averaged over",
            "five independent runs.}",
            "\\label{tab:redundancy}",
            "\\resizebox{\\linewidth}{!}{%",
            "\\begin{tabular}{lrrrr}",
            "\\toprule",
            "Duplicate ratio & Standalone oracle & R-MUR & Sequential oracle & Structural headroom\\\\",
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
            "",
        ]
    )
    write("tab_redundancy.tex", body)


def table_headroom() -> None:
    """Per-dataset headroom from the multi-target oracle audit records."""

    roots = sorted((ROOT / "results/raw").glob("R080a_multitarget_oracle_s5_*"))
    rows = []
    total = 0
    seeds = set()
    for dataset in DATASETS:
        ratios, raw = [], []
        for root in roots:
            for run_dir in sorted(root.glob(f"{dataset}_s*")):
                records_path = run_dir / "records.json"
                if not records_path.exists():
                    continue
                for record in json.loads(records_path.read_text(encoding="utf-8")):
                    seeds.add(int(record["seed"]))
                    ratios.append(float(record["state_conditioning_headroom"]))
                    raw.append(
                        float(record["gain_base_to_oracle_greedy"])
                        - float(record["gain_base_to_oracle_static"])
                    )
        if not ratios:
            continue
        ratios = np.asarray(ratios)
        raw = np.asarray(raw)
        total += ratios.size
        rows.append(
            "{} & {} & {} & {} & {:.3f} \\\\".format(
                LABELS[dataset],
                fmt(float(ratios.mean())),
                fmt(float(np.median(ratios))),
                fmt(float(raw.mean())),
                float(np.mean(ratios > 0)),
            )
        )
    body = "\n".join(
        [
            "% source: results/raw/R080a_multitarget_oracle_s5_*/<dataset>_s*/records.json",
            "\\begin{table}[t]",
            "\\centering",
            "\\small",
            "\\caption{Structural headroom per dataset over 32 fixed targets and",
            f"{len(seeds)} independent runs ({total} target-run evaluations). The ratio and",
            "the unnormalised difference are reported together; every evaluation has positive",
            "headroom.}",
            "\\label{tab:headroom-real}",
            "\\resizebox{\\linewidth}{!}{%",
            "\\begin{tabular}{lrrrr}",
            "\\toprule",
            "Dataset & Mean $H_{\\mathrm{state}}$ & Median $H_{\\mathrm{state}}$ & Mean gap & Positive fraction\\\\",
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
            "",
        ]
    )
    write("tab_headroom.tex", body)


def table_deployable(seeds) -> dict[str, dict[str, float]]:
    per_dataset: dict[str, dict[str, float]] = {}
    extra = [(key, label) for key, label in SUBSET_BASELINES if subset_baseline_root() is not None]
    fixed = [(key, label) for key, label in FIXED_SET_BASELINES if fixed_set_root() is not None]
    oneshot = [ONESHOT_BASELINE] if oneshot_root() is not None else []
    rows_spec = list(DEPLOYABLE) + oneshot + extra + fixed
    ranks = {key: [] for key, _ in rows_spec}
    negative_transfer = {key: [] for key, _ in rows_spec}
    for dataset in DATASETS:
        per_target = load_r080b_targets(dataset, seeds)
        subset = load_subset_baselines(dataset, seeds)
        fixed_set = load_fixed_set_baselines(dataset, seeds)
        oneshot = load_oneshot_baseline(dataset, seeds)
        sources = {key: per_target for key, _ in DEPLOYABLE}
        sources.update({key: subset for key, _ in SUBSET_BASELINES})
        sources.update({key: fixed_set for key, _ in FIXED_SET_BASELINES})
        sources.update({ONESHOT_BASELINE[0]: oneshot})
        means = {}
        for key, _label in rows_spec:
            source = sources[key]
            target_means = [float(np.mean(bucket[key])) for bucket in source.values() if key in bucket]
            means[key] = float(np.mean(target_means)) if target_means else float("nan")
        per_dataset[dataset] = means
        order = sorted(means, key=lambda k: -means[k])
        for position, key in enumerate(order, start=1):
            ranks[key].append(position)
        for key, _label in rows_spec:
            source = sources[key]
            rates = [
                float(np.mean(bucket[f"{key}_ntr"]))
                for bucket in source.values()
                if f"{key}_ntr" in bucket
            ]
            negative_transfer[key].append(float(np.mean(rates)) if rates else float("nan"))

    # A baseline family is only reported once every dataset has its runs, so an
    # in-progress sweep cannot produce a table with empty cells.
    rows_spec = [
        (key, label)
        for key, label in rows_spec
        if all(not np.isnan(per_dataset[d][key]) for d in DATASETS)
    ]

    header = (
        "Method & "
        + " & ".join(LABELS[d] for d in DATASETS)
        + " & Avg. rank & Neg. transfer\\\\"
    )
    rows = []
    for key, label in rows_spec:
        cells = [fmt(per_dataset[d][key]) for d in DATASETS]
        average_rank = float(np.mean(ranks[key]))
        mean_ntr = float(np.nanmean(negative_transfer[key]))
        rows.append(f"{label} & " + " & ".join(cells) + f" & {average_rank:.2f} & {fmt(mean_ntr)}\\\\")
    body = "\n".join(
        [
            "% source: results/raw/R080b_multitarget_rmur_s*/<dataset>/target*_seed*/result.json",
            "% source: results/raw/R202_subset_baselines_s3_*/<dataset>/target*_seed*/result.json",
            "% source: results/raw/R206_fixed_set_baselines_v2_s3_*/<dataset>/target*_seed*/result.json",
            "% source: results/raw/R207_oneshot_response_ablation_s3_*/<dataset>/target*_seed*/result.json",
            "\\begin{table}[t]",
            "\\centering",
            "\\small",
            "\\caption{Deployable selection methods under the multi-target protocol. Values are",
            "prediction gains averaged over 32 fixed targets per dataset and over",
            f"{len(seeds)} independent runs. The first group holds the reference and learned",
            "policies, the second content-based subset rules, and the third fixed-set",
            "acquisition rules. The average rank is computed over all listed methods, and the",
            "final column is the mean negative-transfer rate.}",
            "\\label{tab:deployable}",
            "\\resizebox{\\linewidth}{!}{%",
            "\\begin{tabular}{lrrrrrrrr}",
            "\\toprule",
            header,
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
            "",
        ]
    )
    write("tab_deployable.tex", body)
    return per_dataset


def table_consistency(seeds) -> None:
    header = (
        "Dataset & $\\Delta$ vs Static & $\\Delta$ vs Cached & Positive targets & "
        "$>$ Static & $>$ Cached & Oracle recovery\\\\"
    )
    rows = []
    for dataset in DATASETS:
        per_target = load_r080b_targets(dataset, seeds)
        targets = sorted(per_target)
        delta_static = []
        delta_cached = []
        positive_gain = []
        rmur_all = []
        oracle_all = []
        for target in targets:
            bucket = per_target[target]
            rmur = np.asarray(bucket["ranked_response_q4"], dtype=float)
            static = np.asarray(bucket["static_utility"], dtype=float)
            cached = np.asarray(bucket["cached_mur"], dtype=float)
            oracle = np.asarray(bucket["oracle_greedy"], dtype=float)
            delta_static.append(rmur - static)
            delta_cached.append(rmur - cached)
            positive_gain.append(float(np.mean(rmur)))
            rmur_all.extend(rmur.tolist())
            oracle_all.extend(oracle.tolist())
        stat_mean, stat_lo, stat_hi = hierarchical_bootstrap(delta_static, seed=1)
        cach_mean, cach_lo, cach_hi = hierarchical_bootstrap(delta_cached, seed=2)
        recovery = float(np.sum(rmur_all) / np.sum(oracle_all))
        rows.append(
            "{} & {} [{}, {}] & {} [{}, {}] & {:.3f} & {:.3f} & {:.3f} & {} \\\\".format(
                LABELS[dataset],
                fmt(stat_mean),
                fmt(stat_lo),
                fmt(stat_hi),
                fmt(cach_mean),
                fmt(cach_lo),
                fmt(cach_hi),
                float(np.mean(np.asarray(positive_gain) > 0)),
                float(np.mean([float(np.mean(values)) > 0 for values in delta_static])),
                float(np.mean([float(np.mean(values)) > 0 for values in delta_cached])),
                fmt(recovery, 3),
            )
        )
    body = "\n".join(
        [
            "% source: results/raw/R080b_multitarget_rmur_s*/<dataset>/target*_seed*/result.json",
            "\\begin{table}[t]",
            "\\centering",
            "\\small",
            "\\caption{Multi-target consistency of R-MUR over 32 fixed targets per dataset and",
            f"{len(seeds)} independent runs. Differences are computed per target and then",
            "averaged; brackets are 95\\% hierarchical bootstrap intervals that resample targets",
            "and then runs within a target. Positive targets is",
            "the fraction of targets whose mean gain is positive. Oracle recovery is the pooled",
            "ratio of R-MUR gain to sequential-oracle gain.}",
            "\\label{tab:consistency}",
            "\\resizebox{\\linewidth}{!}{%",
            "\\begin{tabular}{lrrrrrr}",
            "\\toprule",
            header,
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
            "",
        ]
    )
    write("tab_consistency.tex", body)


def table_ablation(seeds) -> None:
    """Component ablation under the multi-target protocol."""

    variants = [
        ("base_only", "Anchor only"),
        ("pool_all", "Pool-all (no selection)"),
        ("cached_mur", "Cached-only router"),
        ("ranked_response_q4", "R-MUR"),
    ]
    rows = []
    stats = {key: {"gain": [], "ntr": [], "contexts": []} for key, _ in variants}
    for dataset in DATASETS:
        per_target = load_r080b_targets(dataset, seeds)
        for key, _label in variants:
            gains, ntrs, contexts = [], [], []
            for bucket in per_target.values():
                if key not in bucket:
                    continue
                gains.append(float(np.mean(bucket[key])))
                ntrs.append(float(np.mean(bucket[f"{key}_ntr"])))
                contexts.append(float(np.mean(bucket[f"{key}_contexts"])))
            if gains:
                stats[key]["gain"].append(float(np.mean(gains)))
                stats[key]["ntr"].append(float(np.mean(ntrs)))
                stats[key]["contexts"].append(float(np.mean(contexts)))
    evaluations = {
        "base_only": "0",
        "pool_all": "100\\%",
        "cached_mur": "0",
        "ranked_response_q4": "25\\%",
    }
    for key, label in variants:
        rows.append(
            "{} & {} & {} & {} & {} \\\\".format(
                label,
                fmt(float(np.mean(stats[key]["gain"]))),
                fmt(float(np.mean(stats[key]["ntr"]))),
                fmt(float(np.mean(stats[key]["contexts"])), 2),
                evaluations[key],
            )
        )
    body = "\n".join(
        [
            "% source: results/raw/R080b_multitarget_rmur_s*/<dataset>/target*_seed*/result.json",
            "\\begin{table}[t]",
            "\\centering",
            "\\small",
            "\\caption{Component ablation under the multi-target protocol, averaged over all",
            "targets and runs of the primary multi-target evaluation, which comprises three",
            "independent runs per target. Predictor evaluations is the share of the candidate",
            "pool that receives a predictor evaluation per decision.}",
            "\\label{tab:ablation}",
            "\\resizebox{\\linewidth}{!}{%",
            "\\begin{tabular}{lrrrr}",
            "\\toprule",
            "Variant & Mean gain & Neg. transfer & Contexts used & Predictor evaluations\\\\",
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}}",
            "\\end{table}",
            "",
        ]
    )
    write("tab_ablation.tex", body)


def main() -> None:
    seeds = common_seeds()
    if not seeds:
        raise SystemExit("no seed completed every dataset yet")
    print(f"using complete seeds: {seeds}")
    table_redundancy()
    table_headroom()
    table_deployable(seeds)
    table_consistency(seeds)
    table_ablation(seeds)
    print(f"wrote tables to {OUT_DIR}")


if __name__ == "__main__":
    sys.exit(main())
