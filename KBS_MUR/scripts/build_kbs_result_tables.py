#!/usr/bin/env python3
"""Generate the KBS result tables directly from immutable raw runs.

The script reads

* ``results/raw/R070_oracle_ladder_*``           controlled redundancy ladder
* ``results/derived/R080a_multitarget_summary``  multi-target oracle headroom
* ``results/raw/R080b_multitarget_rmur_*``       multi-target learned routing
* ``results/derived/R079_six_dataset_summary``   sensor-level shortlist sweep

and writes one ``.tex`` fragment per table into ``paper/tables/``. Each
fragment starts with a provenance comment naming its source. Re-running the
script after new seeds land refreshes the fragments without touching prose.
"""

